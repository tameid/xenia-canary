#!/usr/bin/env bash
# PHASE 0 SPIKE - compile-check the instrumentation patch in a container.
#
# Runs *inside* the container. The repo is mirrored into a container volume, so
# neither the host tree nor the submodules are ever touched. The volume is reused
# between runs, which keeps ninja incremental - the first run pays for the shallow
# submodule clones, later runs only recompile what changed.
#
# Usage (usually called by podman-check.sh):
#   /work/check-build.sh <repo-path> [cmake-target ...]
set -euo pipefail

SRC="${1:?source repo path}"
shift || true
TARGETS=("$@")
if [ ${#TARGETS[@]} -eq 0 ]; then
  TARGETS=(xenia-kernel)
fi

REPO=/work/repo

if [ ! -f "$REPO/.spike-initialized" ]; then
  echo "==> first run: copying $SRC into the work volume"
  rm -rf "$REPO"
  cp -a "$SRC" "$REPO"
  cd "$REPO"
  echo "==> init submodules (shallow)"
  git submodule update --init --depth 1 || git submodule update --init
  touch "$REPO/.spike-initialized"
else
  echo "==> reusing cached work volume, syncing sources"
  # Excluded on purpose:
  #   /third_party/     submodule checkouts -- --delete would re-clone them
  #   */bytecode/       shader bytecode generated *into the source tree* by
  #                     tools/build/compile_shader_spirv.py; deleting it would
  #                     leave the *_spirv.stamp targets satisfied but the headers
  #                     missing, and the build would fail with "file not found".
  rsync -a --delete \
        --exclude '/build/' \
        --exclude '/third_party/' \
        --exclude 'bytecode/' \
        --exclude '/.spike-initialized' \
        --exclude '/.git/modules/' \
        "$SRC/" "$REPO/"
  cd "$REPO"
  # Pick up commits that changed submodule pointers.
  git submodule update --init --depth 1 || true
fi

echo "==> configure"
cmake -B build -G Ninja -DCMAKE_BUILD_TYPE=Release \
      -DCMAKE_C_COMPILER=clang-19 -DCMAKE_CXX_COMPILER=clang++-19 >/dev/null

# xenia-build.py normally generates this before configuring; we invoke cmake
# directly, so replicate it (see generate_version_h in xenia-build.py).
BRANCH="$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo tarball)"
COMMIT="$(git rev-parse HEAD 2>/dev/null || echo unknown)"
SHORT="$(git rev-parse --short HEAD 2>/dev/null || echo unknown)"
cat > build/version.h <<EOF
// Autogenerated by tools/nui-spike/check-build.sh (mirrors xenia-build.py).
#ifndef GENERATED_VERSION_H_
#define GENERATED_VERSION_H_
#define XE_BUILD_BRANCH "$BRANCH"
#define XE_BUILD_COMMIT "$COMMIT"
#define XE_BUILD_COMMIT_SHORT "$SHORT"
#define XE_BUILD_DATE __DATE__
#endif  // GENERATED_VERSION_H_
EOF

echo "==> building: ${TARGETS[*]}"
# Regenerate shader bytecode if the headers went missing (see the rsync excludes).
find build -name '*_spirv.stamp' -delete 2>/dev/null || true
ninja -C build "${TARGETS[@]}"

echo "==> OK"